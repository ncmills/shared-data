/**
 * slice.ts — CORPUS-M8 part 1: the per-site export slice.
 *
 *   npx tsx scripts/corpus/slice.ts            write slices/<site>.json for every site in SITES
 *   npx tsx scripts/corpus/slice.ts --check    regenerate in memory; exit 1 on drift or a leak
 *
 * slices/<site>.json = suitability/<site>.json minus every row that site marks eligible "no".
 * A kept row is copied as that site's suitability row (id, eligible, class, fit, flags, reason,
 * provenance) — nothing from another site's file ever enters. Deterministic: rows sorted by id,
 * no timestamps in the body (a row's own provenance.scoredAt is the scorer's stamp, copied as-is),
 * and the header carries the git blob sha of the source suitability file.
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { SITES, gitBlobSha } from "./suitability.ts";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
export const slicePath = (site: string, root = ROOT) => resolve(root, "slices", `${site}.json`);
const srcPath = (site: string, root = ROOT) => resolve(root, "suitability", `${site}.json`);

export function buildSlice(site: string, suitabilityText: string) {
  const s = JSON.parse(suitabilityText);
  const rows = (s.rows as any[]).filter((r) => r.eligible !== "no").sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
  const scored = rows.filter((r) => r.eligible === "scored").length;
  return {
    site,
    format: 1,
    note: "CORPUS-M8 per-site export slice. Generated by scripts/corpus/slice.ts from suitability/<site>.json — never hand-edit. Holds every row the site does NOT mark \"no\", with only that site's own reason, flags, score and provenance. No consumer reads this file yet.",
    source: { file: `suitability/${site}.json`, gitBlobSha: gitBlobSha(suitabilityText), tagger: s.tagger, vocab: s.vocab },
    counts: { rows: rows.length, scored, unreviewed: rows.length - scored, droppedNo: s.rows.length - rows.length },
    rows,
  };
}

/** One row per line, like suitability/<site>.json, so a regeneration diff reads row by row. */
export function renderSlice(s: ReturnType<typeof buildSlice>): string {
  const { rows, ...head } = s;
  const headJson = JSON.stringify(head, null, 2);
  return headJson.slice(0, -2) + ',\n  "rows": [\n' + rows.map((r) => "    " + JSON.stringify(r)).join(",\n") + "\n  ]\n}\n";
}

/** the site tokens a string names, other than `site` — a rule id / rubric / run id is "<site>-…", "rubric-<site>@…", "…-<site>-…" */
function foreignSite(site: string, s: string): string | undefined {
  return SITES.find((o) => o !== site && new RegExp(`(^|[^a-z])${o}([^a-z]|$)`).test(s));
}

/** Content checks on a slice's own bytes: independent of the regenerate-and-diff, so a planted row is caught either way. */
export function contentProblems(site: string, sliceText: string, suitabilityText: string): string[] {
  const out: string[] = [];
  let sl: any;
  try { sl = JSON.parse(sliceText); } catch (e) { return [`slices/${site}.json: not JSON (${(e as Error).message})`]; }
  if (sl.site !== site) out.push(`slices/${site}.json: site is "${sl.site}"`);
  const src = JSON.parse(suitabilityText);
  const noIds = new Set<string>(src.rows.filter((r: any) => r.eligible === "no").map((r: any) => r.id));
  const at = (r: any) => `slices/${site}.json: ${r.id}`;
  const seen = new Set<string>();
  let last = "";
  for (const r of sl.rows ?? []) {
    if (r.id < last) out.push(`${at(r)} out of id order`);
    last = r.id;
    if (seen.has(r.id)) out.push(`${at(r)} duplicated`);
    seen.add(r.id);
    if (r.eligible === "no") out.push(`${at(r)} is eligible "no" — a row ${site} excludes must not be in its slice`);
    else if (noIds.has(r.id)) out.push(`${at(r)} is marked "no" by suitability/${site}.json (rule ${src.rows.find((x: any) => x.id === r.id).reason}) but sits in the slice as "${r.eligible}"`);
    const rules = [r.reason && ["reason", r.reason], ...(r.rules ?? []).map((x: string) => ["rule id", x])].filter(Boolean) as [string, string][];
    for (const [kind, v] of rules) {
      const id = v.split(":")[0];
      const o = foreignSite(site, id);
      if (o) out.push(`${at(r)} carries ${kind} "${id}" which belongs to ${o}, not ${site}`);
      else if (!id.startsWith(`${site}-`)) out.push(`${at(r)} carries ${kind} "${id}" which is not a ${site}- id`);
    }
    const pv = r.provenance;
    if (pv) {
      for (const [kind, v] of [["rubric/rules version", pv.promptOrRulesVersion], ["run id", pv.runId], ["tagger", pv.tagger]] as [string, string | undefined][]) {
        const o = v && foreignSite(site, v);
        if (o) out.push(`${at(r)} carries ${kind} "${v}" from site ${o}, not ${site}`);
      }
    }
    for (const k of Object.keys(r)) if (!["id", "eligible", "class", "fit", "flags", "reason", "rules", "provenance"].includes(k)) out.push(`${at(r)} has unexpected field "${k}"`);
  }
  if (sl.source?.gitBlobSha !== gitBlobSha(suitabilityText)) out.push(`slices/${site}.json: header gitBlobSha ${sl.source?.gitBlobSha} ≠ suitability/${site}.json's ${gitBlobSha(suitabilityText)}`);
  return out;
}

export interface CheckOptions {
  root?: string;
  /** injected slices/<site>.json bytes (positive-control tests); default = read from disk */
  sliceText?: Partial<Record<string, string>>;
  /** skip the "committed equals regenerated" check, so the content checks must catch a planted row on their own */
  skipDrift?: boolean;
}

export function checkSlices(opts: CheckOptions = {}): string[] {
  const root = opts.root ?? ROOT;
  const problems: string[] = [];
  const p = (s: string) => problems.push(s);
  for (const site of SITES) {
    const src = srcPath(site, root);
    if (!existsSync(src)) { p(`suitability/${site}.json: missing (no source for the slice)`); continue; }
    const srcText = readFileSync(src, "utf8");
    const want = renderSlice(buildSlice(site, srcText));
    const sp = slicePath(site, root);
    const have = opts.sliceText?.[site] ?? (existsSync(sp) ? readFileSync(sp, "utf8") : undefined);
    if (have === undefined) { p(`slices/${site}.json: missing — run npx tsx scripts/corpus/slice.ts`); continue; }
    if (!opts.skipDrift && have !== want) p(`slices/${site}.json: stale — run npx tsx scripts/corpus/slice.ts`);
    problems.push(...contentProblems(site, have, srcText));
  }
  return problems;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes("--check")) {
    const problems = checkSlices();
    if (problems.length) {
      for (const x of problems) console.error("✗ " + x);
      console.error(`✗ slices: ${problems.length} problem(s)`);
      process.exit(1);
    }
    console.log(`✓ slices: ${SITES.length} sites, committed slices equal regenerated, no "no" row, no foreign reason/rule/score`);
  } else {
    for (const site of SITES) {
      const out = renderSlice(buildSlice(site, readFileSync(srcPath(site), "utf8")));
      mkdirSync(dirname(slicePath(site)), { recursive: true });
      writeFileSync(slicePath(site), out);
      console.log(`slices/${site}.json  ${JSON.parse(out).rows.length} rows`);
    }
  }
}
